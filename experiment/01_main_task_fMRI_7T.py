#!/usr/bin/python2
# -*- coding: utf-8 -*-
"""
MAIN TASK, fMRI 7T Synesthesia
O.Colizoli, 2026
Five condition blocked design (ABCDE)
Rest period between each block (fixation)
BOLD baseline period beginning and end of the run (fixation)
Small fixation dot is present throughout entire run.
Stimuli are presented twice in each block, but never twice in a row.
The task for the participant is to indicate when a block contained a symbol/letter in ITALICS
This signal is present in 50% of blocks.
Press 'q' to end early!

Stimuli sequences are generated by generate_blocks.py

    Conditions:
    1. Inducing graphemes in black
    2. Non-inducing pseudo graphemes in black
    3. Inducing graphemes in congruent colors
    4. Non-inducing pseudo graphemes in colors (shuffled from condition #3)
    5. Inducing graphemes in incongruent colors (shuffled from condition #3)

anaconda environment psychopy
"""

# Import necessary modules
import os, time # for paths and data
from psychopy import core, visual, event, gui, monitors
import random
import numpy as np
import pandas as pd
# from IPython import embed as shell # for debugging only
import mri_7T_parameters as p # see for timing, stimuli and parameters

#########################################
##############   PARAMS   ###############
#########################################

conditions = ['inducing_black', 'non_inducing_black', 'inducing_congruent', 'non_inducing_color', 'inducing_incongruent'] # names

#Get subject number
g = gui.Dlg()
g.addField('Subject Number:')
g.addField('Run:')
g.show()
subject_ID = int(g.data[0])
run = int(g.data[1])
# in case GUI doesn't work
# subject_ID = 1
# session = 1

if subject_ID:
    random.seed(subject_ID)
    #########################################
    ################ STIMULI ################
    #########################################
    
    # get subject-specifc blocks and stimuli sequences
    df_sequences = pd.read_csv(os.path.join('stimuli_blocks', 'main_task', 'sub-{}_letter_sequences_main_task.csv'.format(subject_ID)))
    df_special = pd.read_csv(os.path.join('stimuli_blocks', 'main_task', 'sub-{}_letter_italics_main_task.csv'.format(subject_ID)))
    df_condition = pd.read_csv(os.path.join('stimuli_blocks', 'main_task', 'sub-{}_block_type_main_task.csv'.format(subject_ID)))
    df_map = pd.read_csv(os.path.join('stimuli_blocks', 'main_task', 'sub-{}_grapheme_color_map_main_task.csv'.format(subject_ID))) # maps graphemes to colors conditions #4,5
    
    # get list
    blocks = df_condition.iloc[0].tolist() # conditions in order of blocks
    
    # get this subject's counterbalanced response key mapping (yes_left or yes_right)
    df_counterbalancing = pd.read_csv(os.path.join('stimuli_blocks', 'counterbalancing.csv'))
    response_map = df_counterbalancing.loc[df_counterbalancing['subject'] == subject_ID, 'response_map'].values[0]
    
    # key_to_answer: which key ('left'/'right') corresponds to which answer ('yes'/'no') for this subject
    if response_map == 'yes_left':
        key_to_answer = {'1': 'yes', '2': 'no'}
        yes_pos, no_pos = (-50, -50), (50, -50)
    else:  # 'yes_right'
        key_to_answer = {'1': 'no', '2': 'yes'}
        yes_pos, no_pos = (50, -50), (-50, -50)
    
    this_subject = pd.read_csv(os.path.join('colors', 'sub-{}_colors.csv'.format(subject_ID)))
    graphemes    = list(this_subject['inducing'])     # synesthesia inducing graphemes
    symbols      = list(this_subject['non_inducing']) # graphemes that don't induce synesthesia
    colors       = this_subject[['r', 'g', 'b']].values.tolist() # colors of the inducing stimuli
    
    # Set-up window:
    mon = monitors.Monitor('myMac15', width=p.screen_width, distance=p.screen_dist)
    mon.setSizePix((p.scnWidth, p.scnHeight))
    win = visual.Window(
        (p.scnWidth, p.scnHeight),
        color = p.white,
        colorSpace = 'rgb255',
        monitor = mon,
        fullscr = not p.debug_mode,
        units = 'pix',
        allowStencil = True,
        autoLog = False
        )
    win.setMouseVisible(False)

    # Set-up stimuli and timing
    instr_top = visual.TextStim(win, color='black', pos=(0.0, 130), wrapWidth=p.ww)
    instr_bottom = visual.TextStim(win, color='black', pos=(0.0, -180), wrapWidth=p.ww)
    
    # Outer circle (grey)
    stim_fix_outer = visual.Circle(win, radius=5, fillColor='grey', lineColor='grey', edges=128)
    # Inner circle (black)
    stim_fix_inner = visual.Circle(win, radius=2, fillColor='black', lineColor='black', edges=128)
    
    stim_word = visual.TextStim(win, color ='black', pos=(0.0, p.ly), height=p.lh) # SET FONT HERE, SCALING
    
    stim_word.fontFiles = [
        os.path.join('font', p.pseudo_regular[0]), 
        os.path.join('font', p.pseudo_italic[0]), 
        os.path.join('font', p.english_regular[0]), 
        os.path.join('font', p.english_italic[0]), 
    ]
    
    # Signal present prompt
    stim_question = visual.TextStim(
        win,
        text='Symbol in italics?',
        pos=(0, 50),
        color='black',
        height=20,
        wrapWidth=p.ww
    )

    # Response options, positioned underneath (side depends on this subject's response_map)
    stim_yes = visual.TextStim(
        win,
        text='yes',
        pos=yes_pos,
        color='black',
        height=20
    )

    stim_no = visual.TextStim(
        win,
        text='no',
        pos=no_pos,
        color='black',
        height=20
    )
    
    #########################################
    ############# INSTRUCTIONS ##############
    #########################################
    welcome_txt_top = "You will see a series of letters and symbols presented on screen.\
    \nYour task is to view the letters and symbols and notice if any of them are presented in ITALICS.\
    \n\nA question will appear after each series of word strings, exactly like the example below:"

    welcome_txt_bottom = "At that time, you can respond with a button press.\
    \n\nMaintain eye-fixation at the center of the screen at all times\
    \n(even when there are no symbols/words).\
    \n\nLay as still as possible for the duration of the scan session\
    \n(that includes between scans!)\
    \n\n[Waiting for scanner...]"
    
    #######################    
    ####### Output ########
    #######################
    ## Create LogFile folder cwd/LogFiles
    cwd = os.getcwd()
    logfile_dir = os.path.join(cwd, 'sourcedata', 'sub-{}'.format(subject_ID), 'func')  # system independent
    
    if not os.path.isdir(logfile_dir): # make the folder if it doesn't exist already
        os.makedirs(logfile_dir)
    
    ## output file name with time stamp prevents any overwriting of data
    timestr = time.strftime("%Y%m%d-%H%M%S") 
    # bids format    
    output_filename = os.path.join(logfile_dir, 'sub-{}_task-main_run-{}_events_{}.tsv'.format(subject_ID, run, timestr))
 
    cols = ['subject',
              'run',
              'block',
              'trial_type',
              'trial_type_idx',
              'trial_number',
              'letter',
              'font',
              'r',
              'g',
              'b',
              'onset',
              'duration',
              'signal_present',
              'response',
              'RT',
              'correct'
          ]
      
    DF = pd.DataFrame(columns=cols) # output dataframe
    
    #########################################
    ############## MAIN FUNCS ###############
    #########################################

    # define clock!
    clock = core.Clock()
    
    #####################################
    # Instructions, waiting for scanner #
    #####################################
    clock.reset() # important NOT to reset clock after this!
    instr_top.setText(welcome_txt_top)
    instr_bottom.setText(welcome_txt_bottom)

    instr_top.draw()
    stim_fix_outer.draw()
    stim_fix_inner.draw()
    stim_question.draw()
    stim_yes.draw()
    stim_no.draw()
    instr_bottom.draw()
    win.flip()
    
    ########################
    ### WAIT FOR TRIGGER ###
    ########################
    # First pulse
    # respond = event.waitKeys(keyList=p.trigger_key, timeStamped=clock)
    respond = p.waitForTrigger(clock)
    key_pressed, first_pulse = respond[0] # in seconds
    ##################################
    
    ####################################
    # BOLD BASELINE (BEGINNING OF RUN) #
    ####################################
    stim_fix_outer.draw()
    stim_fix_inner.draw()
    win.flip()
    # For quitting early
    respond = event.waitKeys(maxWait=p.t_bold_baseline, keyList=['q'])
    if respond:
        key_pressed, latency = respond[0]
        if key_pressed == 'q':
            core.quit()

    ##################
    #### MAIN LOOP ###
    ##################
    counter_main = 0 

    for b in range(len(blocks)):
        """
        Conditions:
        1. Inducing graphemes in black
        2. Non-inducing pseudo graphemes in black
        3. Inducing graphemes in congruent colors
        4. Non-inducing pseudo graphemes in colors from condition #3
        5. Inducing graphemes in incongruent colors
        
        conditions = ['inducing_black', 'non_inducing_black', 'inducing_congruent', 'non_inducing_color', 'inducing_incongruent'] # names
        
        """
        
        condition_idx = blocks[b]
        condition = conditions[blocks[b]]
        # get grapheme-color map
        this_map = df_map['block_{}'.format(b)].to_list() # grapheme-color mapping for current block (np.nan for conditions 1-3)
        this_sequence = df_sequences['block_{}'.format(b)].to_list() # the stimuli in order for current block
        this_special = df_special['block_{}'.format(b)].to_list() # the signal present list for current block
        
        ########################
        ### WAIT FOR TRIGGER ###
        ########################
        if p.fmri_mode:
            p.waitForTrigger(clock)  # also clears events      
        
        #########################
        # loop trials per block #
        ######################### 
        for t_block, this_grapheme_idx in enumerate(this_sequence):        
            
            ### TO DO ### CODE STIMULI BASED ON CONDITION!!!
            # Define stimuli and variables according to block type
            signal_present = this_special[t_block] # signal present in current trial?
            
            # Condition 1
            if condition == 'inducing_black':  # graphemes that induce synesthesia in black
                this_grapheme = graphemes[this_grapheme_idx] # inducing
                this_color = np.array([0,0,0])               # black
                if signal_present:
                    stim_word.font = p.english_italic[1]
                else:
                    stim_word.font = p.english_regular[1]
                    
            # Condition 2
            elif condition == 'non_inducing_black': # graphemes that do not induce synesthesia in black
                this_grapheme = symbols[this_grapheme_idx] # non_inducing
                this_color = np.array([0,0,0])               # black
                if signal_present:
                    stim_word.font = p.pseudo_italic[1]
                else:
                    stim_word.font = p.pseudo_regular[1]
                    
            # Condition 3                
            elif condition == 'inducing_congruent': # graphemes that induce synesthesia in their congruent colors
                this_grapheme = graphemes[this_grapheme_idx] # inducing
                this_color = np.array(colors[this_grapheme_idx]) # congruent color grapheme1 with color1 etc.
                if signal_present:
                    stim_word.font = p.english_italic[1]
                else:
                    stim_word.font = p.english_regular[1]
                    
            # Condition 4                
            elif condition == 'non_inducing_color': # graphemes that induce synesthesia in their congruent colors
                this_grapheme = symbols[this_grapheme_idx] # symbols
                this_color = np.array(colors[this_map[t_block]]) # get corresponding color from df_map current block
                if signal_present:
                    stim_word.font = p.pseudo_italic[1]
                else:
                    stim_word.font = p.pseudo_regular[1]
                    
            # Condition 5                
            elif condition == 'inducing_incongruent': # graphemes that induce synesthesia in their congruent colors
                this_grapheme = graphemes[this_grapheme_idx] # inducing
                this_color = np.array(colors[this_map[t_block]]) # get corresponding color from df_map current block
                if signal_present:
                    stim_word.font = p.english_italic[1]
                else:
                    stim_word.font = p.english_regular[1]
                                       
            # Pre grapheme fixation cross (small jitter)
            stim_fix_outer.draw()
            stim_fix_inner.draw() 
            win.flip()
            core.wait(np.random.uniform(*p.t_fix)) # *interval unpacks the interval from the list

            # Present grapheme
            stim_word.setText(this_grapheme)
            stim_word.setColor(this_color, 'rgb255')
            stim_word.draw() 
            stim_fix_outer.draw()
            stim_fix_inner.draw()
            win.flip()
            this_word_time = clock.getTime() - first_pulse # get timing of word with respect to first pulse
            core.wait(p.t_grapheme)

            # Save trial data       
            DF.loc[counter_main] = [subject_ID,     # Subject number
                                run,                # run of task
                                b,                  # Block number
                                condition,          # condition string
                                condition_idx,      # index of condition
                                counter_main,       # trial number in the whole task
                                this_grapheme,          # Grapheme presented in current trial
                                stim_word.font,         # font used
                                int(this_color[0]),      # R
                                int(this_color[1]),      # G
                                int(this_color[2]),      # B
                                this_word_time,     # Word onset with respect to first_pulse
                                p.t_grapheme,         # duration (seconds)  
                                signal_present,      # signal presented current trial
                                np.nan,             # response (N/A for grapheme trials)
                                np.nan,             # RT (N/A for grapheme trials)
                                np.nan              # correct (N/A for grapheme trials)
                                ] 
                                    
            DF.to_csv(output_filename,sep='\t')
            counter_main = counter_main+1
            
            # For quitting early
            pressed = event.getKeys()
            if pressed:
                # q quits the experiment
                if pressed[0] == 'q':
                    core.quit()
        
        #### END OF CURRENT BLOCK ####
        ############################
        ### ADD WAIT FOR TRIGGER ? ###
        ############################
        # stim_fix_outer.draw()
        # stim_fix_inner.draw()
        # win.flip()
        # p.waitForTrigger(clock)  # also clears events      
        
        prompt_onset = np.random.uniform(*p.t_prompt_onset) # time to wait for prompt onset
        
        # fixation only
        stim_fix_outer.draw()
        stim_fix_inner.draw()
        win.flip()
        core.wait(prompt_onset)    
        
        # show prompt + fixation
        stim_question.draw()
        stim_yes.draw()
        stim_no.draw()
        stim_fix_outer.draw()
        stim_fix_inner.draw()
        win.flip()

        prompt_onset_time = clock.getTime() # marks when the prompt appeared, same clock as first_pulse
        event.clearEvents() # clear any leftover keypresses in the buffer before monitoring

        response_key = None
        response_time = np.nan

        # --- Phase 1: prompt visible, monitor for a response ---
        while clock.getTime() - prompt_onset_time < p.t_prompt:
            pressed = event.getKeys(keyList=p.keys + ['q'], timeStamped=clock)
            if pressed:
                key_name, press_time = pressed[0]
                if key_name == 'q':
                    core.quit()
                if response_key is None: # only take the first response
                    response_key = key_name
                    response_time = press_time - first_pulse # RT relative to first_pulse

        # --- Phase 2: prompt gone, fixation only, keep monitoring for the remaining rest period ---
        stim_fix_outer.draw()
        stim_fix_inner.draw()
        win.flip()

        remaining_time = p.t_rest - (prompt_onset + p.t_prompt) # time left in the rest block

        fixation_onset_time = clock.getTime()
        while clock.getTime() - fixation_onset_time < remaining_time:
            pressed = event.getKeys(keyList=p.keys + ['q'], timeStamped=clock)
            if pressed:
                key_name, press_time = pressed[0]
                if key_name == 'q':
                    core.quit()
                if response_key is None: # still only take the FIRST response overall
                    response_key = key_name
                    response_time = press_time - first_pulse

        # Was a signal (italic letter) actually present anywhere in this block?
        signal_in_block = int(any(this_special))

        # Score correctness using this subject's counterbalanced key_to_answer mapping.
        # Correctness does not depend on which phase/RT window the response fell in.
        # No response at all -> RT logged as 'missing', correct = 0
        if response_key is not None:
            response_answer = key_to_answer[response_key]
            correct = int((response_answer == 'yes') == bool(signal_in_block))
        else:
            response_answer = 'missing'
            response_time = np.nan
            correct = 0

        # Save prompt/response as its own row
        DF.loc[counter_main] = [subject_ID,
                                run,
                                b,
                                'prompt',
                                condition_idx,
                                counter_main,
                                np.nan,             # letter (N/A for prompt row)
                                np.nan,             # font (N/A for prompt row)
                                np.nan,             # r (N/A for prompt row)
                                np.nan,             # g (N/A for prompt row)
                                np.nan,             # b (N/A for prompt row)
                                prompt_onset_time - first_pulse, # onset of prompt re: first_pulse
                                p.t_prompt,           # duration prompt was shown
                                signal_in_block,    # was a signal present anywhere in this block
                                response_answer,    # 'yes'/'no'/'missing'
                                response_time,      # RT re: first_pulse, or 'missing'
                                correct             # 1 = correct, 0 = incorrect or missing
                                ]
        DF.to_csv(output_filename, sep='\t')
        counter_main = counter_main + 1
        
    ##############################
    # BOLD BASELINE (END OF RUN) #
    ##############################
    stim_fix_outer.draw()
    stim_fix_inner.draw()
    win.flip()
    core.wait(p.t_bold_baseline)

# Scan time
print('Scan time (s) = {}'.format(clock.getTime() - first_pulse))

# Close-up 
# End of run, take a quick break
stim_word.setText("This run is over! \n\n You can close your eyes for a few seconds.")
stim_word.setColor(np.array([0,0,0]), 'rgb255')
stim_word.draw() 
win.flip()
core.wait(1.5) # just wait max 1 TR for scanner to stop
win.close()
core.quit()
